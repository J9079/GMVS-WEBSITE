for filename in html_files:
    filepath = os.path.join(ROOT_DIR, filename)
    if not os.path.exists(filepath):
        print(f"Skipping {filename}, not found.")
        continue

    with open(filepath, "r", encoding="utf-8") as f:
        content = f.read()

    # 1. Update Top Bar
    if 'class="top-bar-social"' not in content:
        pattern = r'(<button\s+id="lang-toggle-btn")'
        if re.search(pattern, content):
            content = re.sub(pattern, TOP_BAR_SOCIAL + r'\n        \1', content, count=1)
            print(f"[{filename}] Added top bar social links (before lang-toggle).")
        else:
            # Fallback: insert before the closing </div> of top-bar-right
            pattern_fallback = r'(<div class="top-bar-right">[\s\S]*?)(</div>\s*</div>\s*</aside>)'
            if re.search(pattern_fallback, content):
                content = re.sub(pattern_fallback, r'\1' + TOP_BAR_SOCIAL + r'      \2', content, count=1)
                print(f"[{filename}] Added top bar social links (before top-bar-right closing).")
            else:
                print(f"[{filename}] WARNING: top-bar-right not found.")

    # 2. Update Footer: insert after </div>\s*</div> for footer-legal-badges
    if 'class="footer-social-wrapper"' not in content:
        # Match closing of footer-legal-badges
        pattern = r'(<div class="footer-legal-badges">[\s\S]*?</div>)'
        if re.search(pattern, content):
            content = re.sub(pattern, r'\1\n' + FOOTER_SOCIAL, content, count=1)
            print(f"[{filename}] Added footer social links.")
        else:
            print(f"[{filename}] WARNING: footer-legal-badges not found.")

    # 3. Update Mobile Drawer: insert before <div class="mobile-drawer-actions">
    if 'class="mobile-drawer-socials"' not in content:
        pattern = r'(<div class="mobile-drawer-actions">)'
        if re.search(pattern, content):
            content = re.sub(pattern, DRAWER_SOCIAL + r'\n    \1', content, count=1)
            print(f"[{filename}] Added mobile drawer social links.")
        else:
            print(f"[{filename}] WARNING: mobile-drawer-actions not found.")

    # 4. Special for contact.html: add contact-social-card
    if filename == "contact.html" and 'class="contact-social-card"' not in content:
        pattern = r'(<!-- Embedded Map Card -->)'
        if re.search(pattern, content):
            content = re.sub(pattern, CONTACT_CARD + r'\n          \1', content, count=1)
            print(f"[{filename}] Added contact-social-card.")
        else:
            print(f"[{filename}] WARNING: Embedded Map Card comment not found.")

    with open(filepath, "w", encoding="utf-8") as f:
        f.write(content)

